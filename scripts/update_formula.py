"""Generate the Homebrew formula for the hwp2md release executables.

Usage: python scripts/update_formula.py --version X.Y.Z [--sums PATH | --sums-url URL]
                                        [--repo OWNER/NAME] [--out PATH]

Reads a release ``SHA256SUMS`` (local file, URL, or by default the one attached
to ``v<version>`` of ``<repo>``) and writes ``Formula/hwp2md.rb`` for the tap
repository to ``--out`` (default stdout). Standard library only. The same input
always gives byte-identical output.

Exit codes: 0 success (stderr ``update_formula: OK <out|-> version=<v>``),
1 malformed SHA256SUMS, missing required asset or download failure
(one ``update_formula: FAIL ...`` line on stderr), 2 usage error.
"""

from __future__ import annotations

import argparse
import re
import sys
import urllib.request
from pathlib import Path

DEFAULT_REPO = "ilyos-numon/hwp2md"
VERSION_RE = re.compile(r"^\d+\.\d+\.\d+$")
REPO_RE = re.compile(r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$")
SUM_LINE_RE = re.compile(r"^(?P<digest>[0-9a-f]{64})  (?P<name>\S+)$")
REQUIRED_ASSETS = ("hwp2md-macos-arm64", "hwp2md-macos-x64", "hwp2md-linux-x64")
DOWNLOAD_TIMEOUT = 30

TEMPLATE = """\
# Generated by scripts/update_formula.py in {repo}. Do not edit by hand.
class Hwp2md < Formula
  desc "Convert Korean HWP, HWPX and HWPML documents to Markdown"
  homepage "https://github.com/{repo}"
  version "{version}"
  license "MIT"

  on_macos do
    on_arm do
      url "{base}/hwp2md-macos-arm64"
      sha256 "{macos_arm64}"
    end
    on_intel do
      url "{base}/hwp2md-macos-x64"
      sha256 "{macos_x64}"
    end
  end

  on_linux do
    on_intel do
      url "{base}/hwp2md-linux-x64"
      sha256 "{linux_x64}"
    end
  end

  def install
    bin.install Dir["hwp2md-*"].first => "hwp2md"
  end

  test do
    assert_match "hwp2md #{{version}}", shell_output("#{{bin}}/hwp2md --version")
    (testpath/"note.txt").write "not a hwp document"
    output = shell_output("#{{bin}}/hwp2md #{{testpath}}/note.txt -o #{{testpath}}/out 2>&1", 3)
    assert_match "not an HWP 5.0 file", output
  end
end
"""


class FormulaError(Exception):
    """A SHA256SUMS problem; the message is the text after ``update_formula: FAIL``."""


def parse_sums(text: str) -> dict[str, str]:
    """Parse ``<64 lowercase hex>  <name>`` lines into ``{name: digest}``.

    Blank lines are ignored. Raises FormulaError(``bad line <n>``) on any other line.
    """
    sums: dict[str, str] = {}
    for number, line in enumerate(text.splitlines(), start=1):
        if not line.strip():
            continue
        match = SUM_LINE_RE.match(line)
        if match is None:
            raise FormulaError(f"bad line {number}")
        sums[match["name"]] = match["digest"]
    return sums


def render_formula(version: str, repo: str, sums: dict[str, str]) -> str:
    """Return the formula text. Raises FormulaError(``missing <asset>``)."""
    for asset in REQUIRED_ASSETS:
        if asset not in sums:
            raise FormulaError(f"missing {asset}")
    return TEMPLATE.format(
        repo=repo,
        version=version,
        base=f"https://github.com/{repo}/releases/download/v{version}",
        macos_arm64=sums["hwp2md-macos-arm64"],
        macos_x64=sums["hwp2md-macos-x64"],
        linux_x64=sums["hwp2md-linux-x64"],
    )


def _download(url: str) -> str:
    try:
        with urllib.request.urlopen(url, timeout=DOWNLOAD_TIMEOUT) as response:
            data: bytes = response.read()
        return data.decode("utf-8")
    except (OSError, UnicodeDecodeError, ValueError) as exc:
        raise FormulaError(f"download {url}: {exc}") from exc


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="update_formula")
    parser.add_argument("--version", required=True, help="release version X.Y.Z (no leading v)")
    source = parser.add_mutually_exclusive_group()
    source.add_argument("--sums", help="local SHA256SUMS file")
    source.add_argument("--sums-url", help="SHA256SUMS URL (default: the release asset)")
    parser.add_argument("--repo", default=DEFAULT_REPO, help="OWNER/NAME of the release repo")
    parser.add_argument("--out", help="output file (default stdout)")
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:
        return 2 if exc.code not in (None, 0) else 0

    version: str = args.version
    repo: str = args.repo
    if not VERSION_RE.match(version):
        print(f"update_formula: bad --version {version!r} (expected X.Y.Z)", file=sys.stderr)
        return 2
    if not REPO_RE.match(repo):
        print(f"update_formula: bad --repo {repo!r} (expected OWNER/NAME)", file=sys.stderr)
        return 2

    try:
        if args.sums is not None:
            sums_path = Path(args.sums)
            if not sums_path.is_file():
                print(f"update_formula: --sums file not found: {sums_path}", file=sys.stderr)
                return 2
            text = sums_path.read_text(encoding="utf-8")
        else:
            url: str = args.sums_url or (
                f"https://github.com/{repo}/releases/download/v{version}/SHA256SUMS"
            )
            text = _download(url)
        formula = render_formula(version, repo, parse_sums(text))
    except FormulaError as exc:
        print(f"update_formula: FAIL {exc}", file=sys.stderr)
        return 1

    if args.out is None:
        sys.stdout.write(formula)
        sys.stdout.flush()
        shown = "-"
    else:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(formula.encode("utf-8"))
        shown = str(out)
    print(f"update_formula: OK {shown} version={version}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
