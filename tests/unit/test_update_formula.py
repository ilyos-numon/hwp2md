"""Unit tests for scripts/update_formula.py (Homebrew formula generator)."""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path
from types import ModuleType

import pytest

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts" / "update_formula.py"

ARM = "a" * 64
INTEL = "b" * 64
LINUX = "c" * 64
WIN = "d" * 64
SUMS = (
    f"{LINUX}  hwp2md-linux-x64\n"
    f"{ARM}  hwp2md-macos-arm64\n"
    f"{INTEL}  hwp2md-macos-x64\n"
    f"{WIN}  hwp2md-windows-x64.exe\n"
)
BASE_URL = "https://github.com/ilyos-numon/hwp2md/releases/download/v0.1.4"


def _load() -> ModuleType:
    spec = importlib.util.spec_from_file_location("update_formula", SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["update_formula"] = module
    spec.loader.exec_module(module)
    return module


uf = _load()


def _write_sums(tmp_path: Path, text: str = SUMS) -> Path:
    path = tmp_path / "SHA256SUMS"
    path.write_text(text, encoding="utf-8")
    return path


def test_render_contains_version_urls_and_hashes(tmp_path: Path) -> None:
    out = tmp_path / "hwp2md.rb"
    rc = uf.main(["--version", "0.1.4", "--sums", str(_write_sums(tmp_path)), "--out", str(out)])
    assert rc == 0
    text = out.read_text(encoding="utf-8")
    assert text.startswith(
        "# Generated by scripts/update_formula.py in ilyos-numon/hwp2md. Do not edit by hand.\n"
        "class Hwp2md < Formula\n"
    )
    assert '  version "0.1.4"\n' in text
    for asset, digest in (
        ("hwp2md-macos-arm64", ARM),
        ("hwp2md-macos-x64", INTEL),
        ("hwp2md-linux-x64", LINUX),
    ):
        assert f'url "{BASE_URL}/{asset}"\n      sha256 "{digest}"\n' in text
    assert "windows" not in text
    assert WIN not in text
    assert text.endswith("  end\nend\n")


def test_parse_sums_and_render_are_deterministic() -> None:
    sums = uf.parse_sums(SUMS)
    assert sums["hwp2md-macos-arm64"] == ARM
    first = uf.render_formula("0.1.4", "ilyos-numon/hwp2md", sums)
    second = uf.render_formula("0.1.4", "ilyos-numon/hwp2md", dict(reversed(sums.items())))
    assert first == second


def test_stdout_output_is_byte_identical(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    sums = str(_write_sums(tmp_path))
    assert uf.main(["--version", "0.1.4", "--sums", sums]) == 0
    first = capsys.readouterr()
    assert uf.main(["--version", "0.1.4", "--sums", sums]) == 0
    second = capsys.readouterr()
    assert first.out == second.out
    assert first.out.startswith("# Generated by")
    assert "update_formula: OK - version=0.1.4" in first.err


def test_missing_asset_exits_1(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    text = "".join(line + "\n" for line in SUMS.splitlines() if "macos-x64" not in line)
    rc = uf.main(["--version", "0.1.4", "--sums", str(_write_sums(tmp_path, text))])
    assert rc == 1
    captured = capsys.readouterr()
    assert "update_formula: FAIL missing hwp2md-macos-x64" in captured.err
    assert captured.out == ""


def test_bad_line_exits_1(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    lines = SUMS.splitlines()
    lines[1] = "not-a-hash  hwp2md-macos-arm64"
    text = "\n".join(lines) + "\n"
    rc = uf.main(["--version", "0.1.4", "--sums", str(_write_sums(tmp_path, text))])
    assert rc == 1
    assert "update_formula: FAIL bad line 2" in capsys.readouterr().err


def test_v_prefixed_version_exits_2(tmp_path: Path) -> None:
    rc = uf.main(["--version", "v0.1.4", "--sums", str(_write_sums(tmp_path))])
    assert rc == 2


def test_out_creates_missing_parent(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    out = tmp_path / "tap" / "Formula" / "hwp2md.rb"
    rc = uf.main(["--version", "0.1.4", "--sums", str(_write_sums(tmp_path)), "--out", str(out)])
    assert rc == 0
    assert out.is_file()
    assert f"update_formula: OK {out} version=0.1.4" in capsys.readouterr().err


def test_custom_repo_changes_urls(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    rc = uf.main(
        ["--version", "1.2.3", "--sums", str(_write_sums(tmp_path)), "--repo", "someone/fork"]
    )
    assert rc == 0
    out = capsys.readouterr().out
    assert "https://github.com/someone/fork/releases/download/v1.2.3/hwp2md-linux-x64" in out
    assert 'homepage "https://github.com/someone/fork"' in out
